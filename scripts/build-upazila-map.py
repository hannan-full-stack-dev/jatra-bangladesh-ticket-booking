"""
Turns geoBoundaries ADM3 (the upazilas) into src/data/upazilaMap.js: one SVG path per upazila, and the district it lies in.
Usage: python3 scripts/build-upazila-map.py path/to/geoBoundaries-BGD-ADM2-all path/to/geoBoundaries-BGD-ADM3-all
Boundaries courtesy of geoBoundaries.org (Runfola et al. 2020, https://doi.org/10.1371/journal.pone.0231866)
Run scripts/build-places.py first: upazilas get their id from src/data/places.js.

The paths are drawn in the same frame as the main map but 8 times bigger and as whole numbers, so a zoomed-in view stays sharp.
This file is large, so the app loads it only when a place needs it.
"""
import json, os, sys
from geotopo import *

SCALE = 8
TOL = 0.003           # degrees, about 330 m
MIN_AREA = 0.00002    # square degrees, drops specks (the biggest piece of every upazila is always kept)

adm2, adm3 = sys.argv[1:3]

# Districts, to say which district every upazila is in.
district_ids = {r[1]: r[0] for r in places_const('DISTRICT_ROWS')}
dist_rings = []
for f in json.load(open(find(adm2, 'geojson')))['features']:
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    dist_rings.append((district_ids[district_name(f['properties']['shapeName'])], [p[0] for p in polys]))

def district_at(lng, lat):
    for did, rings in dist_rings:
        if any(inside(lng, lat, r) for r in rings): return did
    # Just off the coast: take the district whose border is closest.
    return min(dist_rings, key=lambda d: min((p[0] - lng) ** 2 + (p[1] - lat) ** 2 for r in d[1] for p in r))[0]

# The id of an upazila is found by its position: build-places.py wrote the same centre into places.js.
by_centre = {(r[2], r[3]): r[0] for r in places_const('UPAZILA_ROWS')}
assert len(by_centre) == 544
centre_of = {}
for f in json.load(open(find(adm3, 'geojson')))['features']:
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    big = max((p[0] for p in polys), key=area)
    lng, lat = centroid(big)
    if not inside(lng, lat, big): lng, lat = big[len(big) // 2][:2]
    centre_of[f['properties']['shapeID']] = (lng, lat, by_centre[(round(lat, 4), round(lng, 4))])

topo = json.load(open(find(adm3, 'topojson')))
arcs = [simplify_arc(a, TOL) for a in decode_arcs(topo)]

def path(rings):
    out = []
    for r in rings:
        pts = []
        for p in r[:-1]:
            q = tuple(round(v) for v in px(*p, SCALE))
            if not pts or q != pts[-1]: pts.append(q)
        if len(pts) < 3: continue
        steps = ' '.join(f'{b[0] - a[0]} {b[1] - a[1]}' for a, b in zip(pts, pts[1:]))
        out.append(f'M{pts[0][0]} {pts[0][1]}l{steps}z')
    return ''.join(out)

result = {}
for g in list(topo['objects'].values())[0]['geometries']:
    lng, lat, uid = centre_of[g['properties']['shapeID']]
    rings = [ring_points(r, arcs) for poly in polygons(g) for r in poly]
    rings = [r for r in rings if len(r) >= 4]
    big = max(rings, key=area)
    rings = [r for r in rings if r is big or area(r) >= MIN_AREA]
    result[uid] = [district_at(lng, lat), path(rings)]
assert len(result) == 544, len(result)

out = f"""// Generated by scripts/build-upazila-map.py. Do not edit by hand.
// Administrative boundaries courtesy of geoBoundaries.org (Runfola et al. 2020).
// Loaded on demand. Paths are in the main map's frame times SCALE, as whole numbers (M x y, then relative l steps).
export const SCALE = {SCALE}

/** Upazila id (same ids as places.js) to [district id, SVG path]. */
export const UPAZILAS = {json.dumps(result, separators=(',', ':'))}
"""
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'upazilaMap.js'), 'w', encoding='utf-8').write(out)
print('size KB', len(out) // 1024, 'upazilas', len(result), 'districts used', len({v[0] for v in result.values()}))
